export const THIRD_PLACE_MATRIX_COLUMNS = ["1A", "1B", "1D", "1E", "1G", "1I", "1K", "1L"];

export function getThirdPlaceMatrixKey(groups) {
  return [...new Set(groups)].sort().join("");
}

export function getThirdPlaceAssignment(groups) {
  const key = getThirdPlaceMatrixKey(groups);
  return THIRD_PLACE_MATRIX[key] ?? null;
}

export function validateThirdPlaceMatrix() {
  const entries = Object.entries(THIRD_PLACE_MATRIX);
  const errors = [];
  if (entries.length !== 495) errors.push(`La matriz tiene ${entries.length} filas; deberían ser 495.`);
  entries.forEach(([key, row]) => {
    if (key.length !== 8) errors.push(`Key inválida: ${key}`);
    THIRD_PLACE_MATRIX_COLUMNS.forEach((column) => {
      const value = row[column];
      if (!/^3[A-L]$/.test(value || "")) errors.push(`Valor inválido en ${key}.${column}: ${value}`);
      if (value && !key.includes(value.slice(1))) errors.push(`Valor ${value} no pertenece a la combinación ${key}.`);
    });
  });
  return { valid: errors.length === 0, errors };
}
